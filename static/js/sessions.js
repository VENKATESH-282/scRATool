// Analysis Workspaces & Session Token Controller
const SessionsController = {
  currentSession: null,

  async init() {
    this.bindEvents();
    await this.resolveInitialSession();
    this.loadRecentSessions();
  },

  bindEvents() {
    // Copy token button in top header
    const copyBtn = document.getElementById("btn-copy-token");
    if (copyBtn) {
      copyBtn.addEventListener("click", () => this.copyTokenToClipboard());
    }

    // Modal open button in top header
    const modalBtn = document.getElementById("btn-sessions-modal");
    if (modalBtn) {
      modalBtn.addEventListener("click", () => this.openModal());
    }

    // Modal close button and backdrop
    const modal = document.getElementById("sessions-modal");
    const closeBtn = document.getElementById("sessions-modal-close-btn");
    if (closeBtn) {
      closeBtn.addEventListener("click", () => this.closeModal());
    }
    if (modal) {
      modal.addEventListener("click", (e) => {
        if (e.target === modal) this.closeModal();
      });
    }

    // Modal copy token button
    const modalCopyBtn = document.getElementById("btn-modal-copy-token");
    if (modalCopyBtn) {
      modalCopyBtn.addEventListener("click", () => this.copyTokenToClipboard());
    }

    // Modal duplicate button
    const modalDupBtn = document.getElementById("btn-modal-duplicate");
    if (modalDupBtn) {
      modalDupBtn.addEventListener("click", () => this.duplicateCurrentSession());
    }

    // Modal create new workspace button
    const newSessionBtn = document.getElementById("btn-create-new-session");
    if (newSessionBtn) {
      newSessionBtn.addEventListener("click", () => this.promptCreateNewSession());
    }

    // Modal switch by token input & button
    const switchBtn = document.getElementById("btn-do-switch-token");
    const switchInput = document.getElementById("input-switch-token");
    if (switchBtn && switchInput) {
      const doSwitch = () => {
        const val = switchInput.value.trim();
        if (val) this.switchSession(val);
      };
      switchBtn.addEventListener("click", doSwitch);
      switchInput.addEventListener("keydown", (e) => {
        if (e.key === "Enter") doSwitch();
      });
    }
  },

  getToken() {
    return this.currentSession ? this.currentSession.token : null;
  },

  async resolveInitialSession() {
    // 1. Check URL param ?token=... (explicit user navigation or bookmark)
    const urlParams = new URLSearchParams(window.location.search);
    const urlToken = urlParams.get("token");

    if (urlToken) {
      try {
        const res = await fetch(`/api/sessions/${encodeURIComponent(urlToken)}`);
        if (res.ok) {
          const data = await res.json();
          this.setActiveSession(data);
          return;
        }
      } catch (e) {
        console.warn("Could not load specified session from URL:", e);
      }
    }

    // 2. Use fresh token generated by server for this visit
    if (window.__INITIAL_TOKEN__) {
      try {
        const res = await fetch(`/api/sessions/${encodeURIComponent(window.__INITIAL_TOKEN__)}`);
        if (res.ok) {
          const data = await res.json();
          this.setActiveSession(data);
          return;
        }
      } catch (e) {
        console.warn("Could not load server-provided session token:", e);
      }
    }

    // 3. Fallback: generate a brand new session workspace directly
    try {
      const res = await fetch("/api/sessions", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ name: "Analysis Workspace" })
      });
      if (res.ok) {
        const data = await res.json();
        this.setActiveSession(data);
      }
    } catch (e) {
      console.error("Failed to initialize session workspace:", e);
    }
  },

  async createNewSessionDirect() {
    try {
      const res = await fetch("/api/sessions", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ name: "Analysis Workspace" })
      });
      if (res.ok) {
        const data = await res.json();
        await this.switchSession(data.token);
        this.showToast(`New Workspace Session: ${data.token}`);
      }
    } catch (e) {
      console.error("Failed to create new session workspace:", e);
    }
  },

  setActiveSession(session) {
    this.currentSession = session;
    const token = session.token;
    localStorage.setItem("scratool_active_token", token);

    // Sync URL without full page reload
    const currentUrl = new URL(window.location);
    if (currentUrl.searchParams.get("token") !== token) {
      currentUrl.searchParams.set("token", token);
      window.history.replaceState({}, "", currentUrl.toString());
    }

    // Update UI elements in Header
    const tokenCodeEl = document.getElementById("header-session-token");
    if (tokenCodeEl) {
      tokenCodeEl.textContent = token;
      tokenCodeEl.title = `Active Session: ${session.name} (${token})`;
    }

    // Update modal elements
    const modalNameEl = document.getElementById("modal-active-session-name");
    const modalTokenEl = document.getElementById("modal-active-session-token");
    if (modalNameEl) modalNameEl.textContent = session.name || "Analysis Workspace";
    if (modalTokenEl) modalTokenEl.textContent = token;

    // Update Dashboard workspace summary if present
    const dashSessionName = document.getElementById("dash-session-name");
    const dashSessionToken = document.getElementById("dash-session-token");
    if (dashSessionName) dashSessionName.textContent = session.name || "Analysis Workspace";
    if (dashSessionToken) dashSessionToken.textContent = token;
  },

  async switchSession(tokenInput) {
    const errorEl = document.getElementById("switch-token-error");
    if (errorEl) {
      errorEl.style.display = "none";
      errorEl.textContent = "";
    }

    try {
      const res = await fetch(`/api/sessions/${encodeURIComponent(tokenInput)}`);
      if (!res.ok) {
        const err = await res.json();
        throw new Error(err.detail || "Session not found");
      }
      const session = await res.json();
      this.setActiveSession(session);
      this.closeModal();

      // Refresh all controllers with new session workspace data
      if (window.SamplesController) window.SamplesController.loadSamplesheet();
      if (window.ParamsController) window.ParamsController.loadSchemaAndPresets();
      if (window.RunnerController && window.App) window.App.fetchRuns();
      if (window.ExplorerController) window.ExplorerController.loadAvailableRuns();
      if (window.App) window.App.fetchSystemStatus();

      this.showToast(`Switched to workspace: ${session.name} (${session.token})`);
    } catch (e) {
      if (errorEl) {
        errorEl.textContent = e.message;
        errorEl.style.display = "block";
      } else {
        alert("Error switching session: " + e.message);
      }
    }
  },

  async promptCreateNewSession() {
    const name = prompt("Enter a name for the new workspace (or leave blank):", `Workspace ${new Date().toLocaleDateString()}`);
    if (name === null) return; // User cancelled

    try {
      const res = await fetch("/api/sessions", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ name: name.trim() || undefined })
      });
      if (!res.ok) throw new Error("Failed to create workspace");
      const session = await res.json();
      this.setActiveSession(session);
      this.closeModal();

      if (window.SamplesController) window.SamplesController.loadSamplesheet();
      if (window.ParamsController) window.ParamsController.loadSchemaAndPresets();
      if (window.RunnerController && window.App) window.App.fetchRuns();
      if (window.ExplorerController) window.ExplorerController.loadAvailableRuns();
      if (window.App) window.App.fetchSystemStatus();

      this.showToast(`Created new workspace: ${session.name}`);
    } catch (e) {
      alert("Error creating workspace: " + e.message);
    }
  },

  async duplicateCurrentSession() {
    if (!this.currentSession) return;
    const baseToken = this.currentSession.token;
    const newName = prompt("Enter a name for the duplicated workspace:", `${this.currentSession.name} (Copy)`);
    if (newName === null) return;

    try {
      const res = await fetch(`/api/sessions/${encodeURIComponent(baseToken)}/duplicate`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ name: newName.trim() || undefined })
      });
      if (!res.ok) throw new Error("Failed to duplicate workspace");
      const session = await res.json();
      this.setActiveSession(session);
      this.closeModal();

      if (window.SamplesController) window.SamplesController.loadSamplesheet();
      if (window.ParamsController) window.ParamsController.loadSchemaAndPresets();
      if (window.RunnerController && window.App) window.App.fetchRuns();
      if (window.ExplorerController) window.ExplorerController.loadAvailableRuns();

      this.showToast(`Duplicated workspace: ${session.name}`);
    } catch (e) {
      alert("Error duplicating workspace: " + e.message);
    }
  },

  async copyTokenToClipboard() {
    const token = this.getToken();
    if (!token) return;

    try {
      if (navigator.clipboard && navigator.clipboard.writeText) {
        await navigator.clipboard.writeText(token);
      } else {
        const textarea = document.createElement("textarea");
        textarea.value = token;
        document.body.appendChild(textarea);
        textarea.select();
        document.execCommand("copy");
        document.body.removeChild(textarea);
      }

      // Visual feedback
      const feedbackEl = document.getElementById("copy-token-feedback");
      if (feedbackEl) {
        const orig = feedbackEl.textContent;
        feedbackEl.textContent = "Copied!";
        setTimeout(() => feedbackEl.textContent = orig, 1500);
      }
      this.showToast(`Copied session token: ${token}`);
    } catch (e) {
      console.error("Failed to copy token:", e);
    }
  },

  async openModal() {
    const modal = document.getElementById("sessions-modal");
    if (modal) modal.classList.add("active");
    await this.loadRecentSessions();
  },

  closeModal() {
    const modal = document.getElementById("sessions-modal");
    if (modal) modal.classList.remove("active");
    const errorEl = document.getElementById("switch-token-error");
    if (errorEl) errorEl.style.display = "none";
  },

  async loadRecentSessions() {
    const tbody = document.getElementById("recent-sessions-tbody");
    if (!tbody) return;

    try {
      const res = await fetch("/api/sessions");
      if (!res.ok) return;
      const sessions = await res.json();

      if (sessions.length === 0) {
        tbody.innerHTML = `<tr><td colspan="4" style="text-align: center; color: #94a3b8; padding: 16px;">No sessions found.</td></tr>`;
        return;
      }

      const activeTok = this.getToken();
      tbody.innerHTML = sessions.map(s => {
        const isActive = s.token === activeTok;
        const lastActiveDate = s.last_accessed ? new Date(s.last_accessed).toLocaleString() : "-";
        return `
          <tr style="${isActive ? 'background: #eff6ff; font-weight: 600;' : ''}">
            <td style="padding: 10px 12px; border-bottom: 1px solid var(--border);">
              ${escapeHtml(s.name)} ${isActive ? '<span style="font-size: 10px; background: #2563eb; color: #fff; padding: 2px 6px; border-radius: 10px; margin-left: 6px;">ACTIVE</span>' : ''}
            </td>
            <td style="padding: 10px 12px; border-bottom: 1px solid var(--border); font-family: monospace;">
              ${escapeHtml(s.token)}
            </td>
            <td style="padding: 10px 12px; border-bottom: 1px solid var(--border); color: var(--text-muted); font-size: 12px;">
              ${lastActiveDate}
            </td>
            <td style="padding: 10px 12px; border-bottom: 1px solid var(--border); text-align: right;">
              ${isActive ? '<span style="color: #2563eb; font-size: 12px;">Current</span>' : `<button class="btn btn-sm btn-outline" onclick="SessionsController.switchSession('${s.token}')">Switch</button>`}
            </td>
          </tr>
        `;
      }).join("");
    } catch (e) {
      console.error("Failed to load recent sessions:", e);
    }
  },

  showToast(msg) {
    let toast = document.getElementById("scratool-toast");
    if (!toast) {
      toast = document.createElement("div");
      toast.id = "scratool-toast";
      toast.style.cssText = `
        position: fixed;
        bottom: 24px;
        right: 24px;
        background: #1e293b;
        color: #f8fafc;
        padding: 12px 20px;
        border-radius: 8px;
        font-size: 13px;
        font-weight: 500;
        box-shadow: 0 10px 25px rgba(0,0,0,0.25);
        z-index: 999999;
        transition: opacity 0.3s ease, transform 0.3s ease;
        opacity: 0;
        transform: translateY(10px);
        pointer-events: none;
      `;
      document.body.appendChild(toast);
    }
    toast.textContent = msg;
    toast.style.opacity = "1";
    toast.style.transform = "translateY(0)";
    clearTimeout(this._toastTimer);
    this._toastTimer = setTimeout(() => {
      toast.style.opacity = "0";
      toast.style.transform = "translateY(10px)";
    }, 3000);
  }
};

function escapeHtml(str) {
  if (!str) return "";
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

window.SessionsController = SessionsController;
